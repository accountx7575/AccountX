import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import {
  validateBusinessName,
  isAutoGeneratedBusinessName,
  isProbeArtefactBusinessName,
  BUSINESS_NAME_MIN_LENGTH,
} from '@/lib/businessNameGuard';

describe('validateBusinessName', () => {
  it('rejects an empty name', () => {
    expect(validateBusinessName('')).toEqual({ ok: false, error: 'Business name is required.' });
    expect(validateBusinessName('   ')).toEqual({ ok: false, error: 'Business name is required.' });
  });

  it('rejects a name that is too short', () => {
    const result = validateBusinessName('A');
    expect(result.ok).toBe(false);
  });

  it('rejects auto-generated placeholder names', () => {
    for (const name of ['Business', 'New Business', 'business 12', 'Test', 'Untitled', 'asdf', 'asdfgh', 'qwer', 'Company 3']) {
      const result = validateBusinessName(name);
      expect(result.ok, `${name} should be refused`).toBe(false);
    }
  });

  it('accepts a real business name and returns it trimmed', () => {
    const result = validateBusinessName('  Sharma Traders  ');
    expect(result).toEqual({ ok: true, value: 'Sharma Traders' });
  });

  it('accepts names that merely contain a blocked word', () => {
    expect(validateBusinessName('Probe Instruments Pvt Ltd').ok).toBe(true);
    expect(validateBusinessName('Asdf Traders').ok).toBe(true);
    expect(validateBusinessName('Test House Restaurant').ok).toBe(true);
  });

  it('treats an empty name as auto-generated', () => {
    expect(isAutoGeneratedBusinessName('')).toBe(true);
    expect(isAutoGeneratedBusinessName('  ')).toBe(true);
    expect(isAutoGeneratedBusinessName('Sharma Traders')).toBe(false);
  });

  it('exposes a minimum length', () => {
    expect(BUSINESS_NAME_MIN_LENGTH).toBeGreaterThan(1);
  });
});

describe('probe artefact names are refused at creation time', () => {
  it('refuses the probe rows that had to be purged from the live project', () => {
    for (const name of ['POS149 Probe Star', 'RLSBoundaryProbe', 'Verify LLP', 'asdf']) {
      expect(validateBusinessName(name).ok, `${name} should be refused`).toBe(false);
    }
    // "asdf" is caught by the auto-generated list, not the probe list.
    expect(isProbeArtefactBusinessName('POS149 Probe Star')).toBe(true);
    expect(isProbeArtefactBusinessName('RLSBoundaryProbe')).toBe(true);
    expect(isProbeArtefactBusinessName('Verify LLP')).toBe(true);
    expect(isProbeArtefactBusinessName('asdf')).toBe(false);
  });

  it('still accepts real company names that contain a similar word', () => {
    for (const name of ['Probe Instruments Pvt Ltd', 'Asdf Traders', 'Test House Restaurant', 'Sharma Traders']) {
      expect(validateBusinessName(name).ok, `${name} should be accepted`).toBe(true);
      expect(isProbeArtefactBusinessName(name), `${name} should not read as a probe artefact`).toBe(false);
    }
  });
});

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      if (entry === 'node_modules' || entry === 'dist') continue;
      walk(full, out);
    } else if (/\.(ts|tsx)$/.test(entry) && !/\.test\.tsx?$/.test(entry)) {
      out.push(full);
    }
  }
  return out;
}

describe('no probe or auto-create logic is compiled into the app', () => {
  const srcDir = join(process.cwd(), 'src');

  it('contains no probe artefacts in source', () => {
    const offenders: string[] = [];
    for (const file of walk(srcDir)) {
      const text = readFileSync(file, 'utf8');
      // A probe artefact is a business-creation call whose payload carries a
      // probe-ish name — a doc comment that merely mentions one is fine.
      const creation = /(from\((['"])businesses\2\)\s*\n?\s*\.insert\(|rpc\(\s*(['"])create_business_with_owner\3)/g;
      let match: RegExpExecArray | null;
      while ((match = creation.exec(text)) !== null) {
        const payload = text.slice(match.index, match.index + 400);
        if (/probe|asdf|verify\s+llp/i.test(payload)) offenders.push(file);
      }
    }
    expect(offenders).toEqual([]);
  });

  it('never inserts a business row outside an explicit submit handler', () => {
    const offenders: string[] = [];
    for (const file of walk(srcDir)) {
      const text = readFileSync(file, 'utf8');
      if (!/from\((['"])businesses\1\)\s*\n?\s*\.insert\(/.test(text)) continue;
      // The only allowed business insert is the Super Admin "Onboard New
      // Business" modal, which is invoked from its own submit handler.
      const allowed = file.replace(/\\/g, '/').endsWith('src/pages/SuperAdminPage.tsx');
      if (!allowed) offenders.push(file);
    }
    expect(offenders).toEqual([]);
  });

  it('creates tenants only through the audited RPC', () => {
    const setup = readFileSync(join(srcDir, 'pages/auth/BusinessSetupPage.tsx'), 'utf8');
    expect(setup).toContain("supabase.rpc('create_business_with_owner'");
    expect(setup).not.toMatch(/from\((['"])businesses\1\)\s*\n?\s*\.insert\(/);
  });
});
