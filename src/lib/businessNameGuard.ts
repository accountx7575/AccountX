/**
 * Guard for the business-name field of every tenant-creation surface
 * (the /setup-business form and the Super Admin "onboard tenant" modal).
 *
 * Why this exists: a tenant row is a real, billable record, and every child
 * table cascades from it. Any code path that creates a business without a
 * human-typed name (an autofill, a seeded default, a probe script) leaves
 * junk tenants behind — the "POS149 Probe Star" / "RLSBoundaryProbe" /
 * "asdf" rows that had to be purged from the live project.
 *
 * The rule is deliberately narrow: real company names pass, and only the
 * obvious machine-generated placeholders are refused.
 */

export const BUSINESS_NAME_MIN_LENGTH = 2;

/** Names that mean "nobody typed this" rather than "this is our company". */
const AUTO_GENERATED_PATTERNS: RegExp[] = [
  /^(my\s+|new\s+|test\s+|demo\s+|sample\s+|temporary\s+|temp\s+)?business(\s*#?\d+)?$/i,
  /^(company|firm|store|shop|trial)(\s*#?\d+)?$/i,
  /^untitled(\s*#?\d+)?$/i,
  /^new\s+tenant(\s*#?\d+)?$/i,
  /^test(\s*#?\d+)?$/i,
  /^(asdf|asdfgh|qwer|qwert|zxcv|abcd|abc|aaa)(\d+)?$/i,
];

/**
 * Artefacts left behind by live probes and scripted checks — the rows that
 * had to be purged from the live project ("POS149 Probe Star",
 * "RLSBoundaryProbe", "Verify LLP"). They are refused AT CREATION TIME now
 * instead of being cleaned up afterwards.
 *
 * The patterns are anchored/tokenised on purpose: a company may legitimately
 * be called "Probe Instruments Pvt Ltd" or "Test House Restaurant", so a bare
 * /probe/ or /test/ rule would refuse real tenants. "asdf" is already refused
 * by the auto-generated list above.
 */
const PROBE_ARTEFACT_PATTERNS: RegExp[] = [
  /^pos\d+/i,
  /\bprobe\s+star\b/i,
  /rls\s*boundary\s*probe/i,
  /\bverify\s+llp\b/i,
];

/** True when the name looks like a probe/test artefact from a scripted run. */
export function isProbeArtefactBusinessName(raw: string): boolean {
  const value = (raw ?? '').trim();
  if (!value) return false;
  return PROBE_ARTEFACT_PATTERNS.some((pattern) => pattern.test(value));
}

export type BusinessNameValidation =
  | { ok: true; value: string }
  | { ok: false; error: string };

/** True when the trimmed name looks machine-generated (or is empty). */
export function isAutoGeneratedBusinessName(raw: string): boolean {
  const value = raw.trim();
  if (!value) return true;
  return AUTO_GENERATED_PATTERNS.some((pattern) => pattern.test(value));
}

/**
 * Validates a business name before it is allowed to create a tenant row.
 * Returns the trimmed name to persist on success.
 */
export function validateBusinessName(raw: string): BusinessNameValidation {
  const value = (raw ?? '').trim();
  if (!value) {
    return { ok: false, error: 'Business name is required.' };
  }
  if (value.length < BUSINESS_NAME_MIN_LENGTH) {
    return { ok: false, error: `Business name must be at least ${BUSINESS_NAME_MIN_LENGTH} characters.` };
  }
  if (isProbeArtefactBusinessName(value)) {
    return { ok: false, error: 'Enter the actual business name — probe and test names are not allowed.' };
  }
  if (isAutoGeneratedBusinessName(value)) {
    return { ok: false, error: 'Enter the actual business name — placeholder names are not allowed.' };
  }
  return { ok: true, value };
}
